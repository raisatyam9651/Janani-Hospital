<p class="post__lede">
  Most women in North Karnataka see a doctor when something is already wrong. The checkups on this page are the
  opposite kind of visit &mdash; short, inexpensive appointments that find a problem years before it becomes an
  emergency. Here is what to book, and when.
</p>

<p>
  A useful way to think about screening is that your body changes what it is likely to get wrong roughly every decade.
  In your twenties the risks are infection, anaemia and untreated menstrual disorders. In your thirties and forties it
  is thyroid disease, diabetes, fibroids and cervical changes. After menopause it is bone loss, blood pressure and
  breast cancer. A screening plan that follows those decades catches far more than an annual blanket test does.
</p>

<h2>In your 20s: establish a baseline</h2>

<p>
  The first gynecology visit does not need a reason. It establishes what normal looks like for you, which is what makes
  a future abnormal result meaningful.
</p>

<ul>
  <li><strong>Complete blood count (CBC) and ferritin.</strong> Iron-deficiency anaemia is extremely common in Indian women of reproductive age, and heavy periods are the usual cause. Persistent tiredness, breathlessness on the stairs or hair fall is worth a blood test, not a supplement bought over the counter.</li>
  <li><strong>Thyroid profile (TSH).</strong> Hypothyroidism often shows up first as weight gain, irregular cycles or difficulty conceiving.</li>
  <li><strong>Pelvic examination and ultrasound</strong> if cycles are irregular, painful, or heavier than about seven days &mdash; the usual findings are PCOS, fibroids or endometriosis, all far easier to manage early.</li>
  <li><strong>HPV vaccination</strong> if it was not given in adolescence. It is still worthwhile up to the mid-twenties, and in some cases beyond.</li>
  <li><strong>Rubella immunity and blood group</strong> before planning a pregnancy.</li>
</ul>

<h2>In your 30s: screening becomes routine</h2>

<p>
  This is the decade in which cervical screening starts and metabolic problems begin to appear &mdash; often silently,
  and often a decade earlier in South Asian women than in Western screening guidelines.
</p>

<ul>
  <li><strong>Pap smear every three years</strong> from age 21, or <strong>HPV DNA testing every five years</strong> from age 30. Cervical cancer is one of the very few cancers that screening can prevent outright, because the pre-cancerous stage lasts years and is treatable in an outpatient visit.</li>
  <li><strong>Fasting blood sugar and HbA1c</strong> annually if there is a family history of diabetes, a previous gestational diabetes, or a BMI above 23.</li>
  <li><strong>Blood pressure at every visit.</strong> Hypertension in women is frequently first detected in pregnancy, then never followed up afterwards.</li>
  <li><strong>Lipid profile</strong> every three to five years, earlier if there is family history of heart disease.</li>
  <li><strong>Breast self-awareness.</strong> Not a formal monthly ritual, but knowing how your breasts normally feel, so that a new lump, skin dimpling or nipple discharge gets reported rather than watched.</li>
</ul>


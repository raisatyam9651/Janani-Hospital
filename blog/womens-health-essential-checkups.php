<h2>In your 40s: the decade that matters most</h2>

<p>
  Symptoms in the forties are easy to dismiss as stress or "just perimenopause". Some of them are. The screening below
  is what separates the two.
</p>

<ul>
  <li><strong>Mammogram every one to two years from 40</strong>, or earlier and with ultrasound if a first-degree relative had breast cancer. Dense breast tissue is common in Indian women, which is why a clinical examination and ultrasound often accompany the mammogram.</li>
  <li><strong>Continue cervical screening</strong> on the same three- or five-yearly cycle.</li>
  <li><strong>Annual diabetes and blood pressure check</strong> &mdash; no longer optional at this age.</li>
  <li><strong>Investigate abnormal bleeding, always.</strong> Bleeding between periods, after intercourse, or unusually heavy flow needs an ultrasound and often a <a href="/department/hysteroscopy.php">hysteroscopy</a>. Perimenopause explains a lot of bleeding changes, but it should be the conclusion after investigation, not instead of it.</li>
  <li><strong>Vitamin D and calcium status</strong>, since bone loss begins well before the last period.</li>
</ul>

<h2>After 50: bones, heart and cancer screening</h2>

<p>
  Oestrogen falls sharply at menopause, and with it goes a good deal of natural protection for bone and heart. The
  screening list shifts accordingly.
</p>

<ul>
  <li><strong>Bone mineral density (DEXA) scan</strong> at menopause or soon after, repeated as advised. A wrist or hip fracture after a minor fall is very often the first sign of osteoporosis that could have been treated years earlier.</li>
  <li><strong>Mammogram every one to two years</strong>, continuing into the sixties.</li>
  <li><strong>Cervical screening until about 65</strong>, provided previous results have been normal.</li>
  <li><strong>Annual lipids, sugar, blood pressure, kidney and liver function</strong> &mdash; the standard components of a <a href="/pages/health-packages.php">preventive health package</a>.</li>
  <li><strong>Any bleeding after menopause is abnormal</strong> and needs assessment promptly. It is often something benign such as atrophy, but it is the main early symptom of endometrial cancer.</li>
</ul>


<p class="post__lede">
  Antenatal care is not a series of unrelated appointments. Each visit is timed because something specific can only be
  detected in that window &mdash; a scan that dates the pregnancy accurately, a test that must fall between 11 and 14
  weeks, a vaccination that has to be given before delivery. This is the full schedule, month by month.
</p>

<p>
  A typical uncomplicated pregnancy involves eight to ten visits. A high-risk pregnancy &mdash; twins, diabetes, high
  blood pressure, a previous caesarean or a previous loss &mdash; involves more, and the schedule below is adjusted
  accordingly by your obstetrician.
</p>

<h2>Before you conceive: the visit most people skip</h2>

<p>
  Ideally three months before trying: folic acid 400 mcg daily (5 mg if there is diabetes, epilepsy or a previous
  neural tube defect), a thyroid check, haemoglobin, blood group with Rh typing, blood sugar, rubella immunity, and a
  review of any regular medication. Neural tube defects form in the first four weeks &mdash; often before a woman knows
  she is pregnant &mdash; which is why folic acid started after a positive test is already late.
</p>

<h2>Month 1&ndash;2 (up to 8 weeks): confirming the pregnancy</h2>

<ul>
  <li>Urine test, then a blood beta-hCG if there is doubt.</li>
  <li><strong>First ultrasound at 6&ndash;8 weeks</strong> to confirm the pregnancy is inside the uterus, count the number of sacs, and check the heartbeat. This also gives the most accurate due date you will ever get &mdash; later scans estimate size, not age.</li>
  <li>Booking bloods: haemoglobin, blood group and Rh, blood sugar, TSH, HIV, hepatitis B, VDRL, urine routine and culture.</li>
  <li>Folic acid continues through the first trimester.</li>
  <li>Discuss nausea, medications to stop, and what is safe for pain relief.</li>
</ul>

<h2>Month 3 (9&ndash;13 weeks): the first-trimester screen</h2>

<ul>
  <li><strong>NT scan at 11&ndash;13 weeks + 6 days.</strong> Measures the fluid at the back of the baby&rsquo;s neck and checks the nasal bone. Combined with the dual marker blood test, it estimates the risk of Down syndrome and two other chromosomal conditions.</li>
  <li>This window is fixed. Miss it and the screening options for the rest of the pregnancy are narrower.</li>
  <li>NIPT (a maternal blood test analysing fetal DNA) may be offered as a more sensitive alternative where indicated.</li>
  <li>Blood pressure, weight, and a discussion about diet and work.</li>
</ul>


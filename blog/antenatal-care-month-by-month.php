<h2>Weight, diet and activity</h2>

<p>
  For a woman starting at a normal BMI, a total gain of 11&ndash;16 kg across the pregnancy is usual; less if
  overweight at booking, more for twins. There is no need to "eat for two" &mdash; the extra requirement is roughly 350
  extra calories a day in the second trimester and 450 in the third, best met with protein, dal, eggs, milk, curd,
  green leafy vegetables and fruit.
</p>

<p>
  Moderate activity &mdash; walking, prenatal yoga, swimming &mdash; is beneficial in an uncomplicated pregnancy.
  Avoid raw or undercooked food, unpasteurised milk, alcohol, tobacco in any form, and self-prescribed medication
  including many common painkillers and Ayurvedic preparations. Check with your doctor before taking anything.
</p>


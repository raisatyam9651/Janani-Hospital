<h2>Month 4&ndash;5 (14&ndash;22 weeks): the anomaly scan</h2>

<ul>
  <li><strong>Anomaly scan (target scan) at 18&ndash;22 weeks.</strong> A detailed examination of the brain, spine, heart, kidneys, limbs, placental position and amniotic fluid. This is the most important scan of the pregnancy.</li>
  <li><strong>First TT / Tdap dose</strong> as advised, with the second four weeks later. Tdap also protects the newborn against whooping cough.</li>
  <li><strong>Iron and calcium supplements begin</strong> after the first trimester, usually 100 mg elemental iron and 500 mg calcium daily &mdash; taken at different times of day, since calcium blocks iron absorption.</li>
  <li>Fetal movements usually begin to be felt between 18 and 22 weeks in a first pregnancy, earlier in later ones.</li>
  <li>Blood pressure, weight, and haemoglobin repeated.</li>
</ul>

<h2>Month 6&ndash;7 (23&ndash;32 weeks): growth and glucose</h2>

<ul>
  <li><strong>Oral glucose tolerance test at 24&ndash;28 weeks</strong> for gestational diabetes. South Asian women have a substantially higher risk, so this is done for everyone, not only those with symptoms or a family history.</li>
  <li><strong>Anti-D injection at 28 weeks</strong> if you are Rh negative and your partner is Rh positive.</li>
  <li><strong>Growth scan around 28&ndash;32 weeks</strong> to check fetal weight, amniotic fluid and placental function.</li>
  <li>Repeat haemoglobin &mdash; anaemia is common at this stage and easier to correct now than at 38 weeks.</li>
  <li>Visits move to every two weeks. Start counting fetal movements daily: most units advise recording ten movements within two hours during the baby&rsquo;s active period.</li>
</ul>

<h2>Month 8 (33&ndash;36 weeks): preparing for delivery</h2>

<ul>
  <li>Growth scan with Doppler if there is any concern about growth or blood pressure.</li>
  <li>Position of the baby is assessed &mdash; a breech presentation at this stage still often turns on its own.</li>
  <li>Group B streptococcus swab where offered.</li>
  <li><strong>Birth plan discussion:</strong> mode of delivery, pain relief options, who will accompany you, and what happens if a caesarean becomes necessary.</li>
  <li>Hospital bag, documents and transport arranged &mdash; particularly important for families travelling in from outside Vijayapura.</li>
</ul>

<h2>Month 9 (37&ndash;40 weeks): weekly reviews</h2>

<ul>
  <li>Weekly visits with blood pressure, urine protein, fundal height and fetal heart monitoring.</li>
  <li>Non-stress test (NST) and amniotic fluid assessment as advised.</li>
  <li>A discussion about induction if the pregnancy passes the due date, and about what labour will actually feel like.</li>
  <li>Confirm signs of labour: regular tightening every five minutes for an hour, leaking fluid, or a bloody show.</li>
</ul>


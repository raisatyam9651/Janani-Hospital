<p class="post__lede">
  Diabetes and hypertension travel together, damage the same organs, and are both almost entirely silent until the
  damage is done. The good news is that they are managed with one shared routine &mdash; a handful of numbers, a
  quarterly test, and a few habits that are easier to sustain than most people fear.
</p>

<p>
  India has one of the largest diabetic populations in the world, and North Karnataka is no exception. What makes the
  condition dangerous here is not the diagnosis but the follow-up: treatment started, then stopped when the patient
  "felt fine", and reviewed again only when there is a foot ulcer, failing vision or a heart attack. This guide is
  about the ordinary maintenance that prevents that.
</p>

<h2>Know your numbers</h2>


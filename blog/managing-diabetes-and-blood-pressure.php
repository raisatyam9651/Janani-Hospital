<p>
  These are typical targets, not universal ones. An older patient with heart disease may be given a deliberately more
  relaxed HbA1c target because hypoglycaemia is the greater danger; a young patient planning pregnancy will be given a
  tighter one. Ask your physician for <em>your</em> number and write it on the front of your file.
</p>

<h2>Measuring blood pressure properly at home</h2>

<p>
  Most home readings are wrong for avoidable reasons. Done correctly, they are more useful than a single clinic reading
  taken after you have climbed the stairs.
</p>

<ul>
  <li>Sit quietly for five minutes first. Back supported, feet flat on the floor, legs uncrossed.</li>
  <li>Arm resting on a table at heart level, cuff on bare skin, not over a sleeve.</li>
  <li>No coffee, tea, tobacco or exercise for 30 minutes before. Empty your bladder first.</li>
  <li>Do not talk during the reading.</li>
  <li>Take two readings a minute apart, morning and evening, and record both. A single high reading is not a diagnosis; a pattern is.</li>
  <li>Use a validated upper-arm digital monitor. Wrist devices are far less reliable.</li>
</ul>

<h2>Food: adapting South Indian meals, not abandoning them</h2>

<p>
  Nobody sustains a diet that removes everything they grew up eating. The changes below keep the plate familiar and
  change what it does to your blood sugar.
</p>

<ul>
  <li><strong>Halve the rice, double the dal and vegetables.</strong> Protein and fibre alongside carbohydrate blunt the sugar spike substantially.</li>
  <li><strong>Prefer whole grains</strong> &mdash; jowar, bajra, ragi, hand-pounded or brown rice &mdash; over polished white rice and refined wheat.</li>
  <li><strong>Eat vegetables or salad first</strong> in the meal. The order genuinely changes the post-meal reading.</li>
  <li><strong>Cut liquid sugar entirely:</strong> sweet tea and coffee, soft drinks, packaged juices. This is usually the single highest-yield change.</li>
  <li><strong>Salt below 5 g a day</strong> for blood pressure. Most of it comes from pickles, papad, packaged snacks and restaurant food rather than the salt shaker.</li>
  <li><strong>Do not skip meals</strong> if you take insulin or sulphonylureas &mdash; skipping is a common cause of dangerous lows.</li>
  <li><strong>Nuts, curd, sprouts and eggs</strong> make better between-meal snacks than biscuits or fried items.</li>
</ul>

<h2>Movement, weight and sleep</h2>

<p>
  Aim for 30 minutes of brisk walking on at least five days a week, plus two sessions of simple resistance work.
  Muscle is where glucose is stored, so building a little of it improves control independently of weight loss. Even a
  5&ndash;10% reduction in body weight can meaningfully lower both sugar and blood pressure.
</p>

<p>
  Sleep matters more than most people expect: persistent short sleep and untreated sleep apnoea both worsen insulin
  resistance and blood pressure. Loud snoring with daytime sleepiness is worth mentioning to your doctor.
</p>

<div class="post__callout">
  <h3><svg class="icon"><use href="#i-check-circle"></use></svg> Taking medication reliably</h3>
  <ul>
    <li>Never stop a medicine because the numbers have normalised &mdash; they are normal <em>because</em> of it.</li>
    <li>Tie each dose to a fixed daily event, and use a weekly pill box.</li>
    <li>Carry a current list of your medicines, with doses, to every appointment and hospital visit.</li>
    <li>Ask before adding any Ayurvedic, homeopathic or herbal product &mdash; several interact with diabetes and blood pressure medication.</li>
    <li>If a dose is missed, take it when you remember unless it is nearly time for the next; do not double up.</li>
  </ul>
</div>

<h2>The complications worth screening for</h2>

<p>
  Diabetes and hypertension damage small blood vessels first. Each of the checks below finds that damage while it is
  still reversible or containable.
</p>

<ul>
  <li><strong>Eyes:</strong> a dilated retinal examination every year. Diabetic retinopathy has no symptoms until vision is already lost.</li>
  <li><strong>Kidneys:</strong> urine albumin and serum creatinine annually. Early protein leak is treatable; established kidney failure is not.</li>
  <li><strong>Feet:</strong> look at your feet daily &mdash; between the toes and under the soles &mdash; and have sensation tested annually. Most amputations begin as a blister or crack that was never felt. Never walk barefoot, indoors or outdoors, and never trim corns yourself.</li>
  <li><strong>Heart:</strong> annual lipids and ECG, with further testing if there is chest discomfort, breathlessness on exertion or unusual fatigue.</li>
  <li><strong>Nerves:</strong> report burning, tingling or numbness in the hands or feet rather than living with it.</li>
  <li><strong>Dental:</strong> a check every six months. Gum disease and poor sugar control feed each other.</li>
</ul>

<div class="post__callout post__callout--warn">
  <h3><svg class="icon"><use href="#i-alert-triangle"></use></svg> Emergencies &mdash; come in immediately</h3>
  <ul>
    <li><strong>Low sugar:</strong> sweating, trembling, confusion, palpitations. Take glucose, sugar or juice at once, then a meal &mdash; and tell your doctor, because the dose needs reviewing.</li>
    <li><strong>Very high sugar:</strong> excessive thirst, heavy urination, vomiting, deep rapid breathing, drowsiness.</li>
    <li><strong>Blood pressure above 180/120</strong> with headache, chest pain, breathlessness or visual disturbance.</li>
    <li><strong>Stroke signs:</strong> sudden facial droop, arm weakness or slurred speech &mdash; call for help immediately, time is the whole treatment.</li>
    <li><strong>Foot:</strong> any wound, blister, black area or spreading redness, however small and however painless.</li>
  </ul>
</div>

<h2>Special situations</h2>

<h3>Fasting during festivals</h3>
<p>
  Fasting is possible for many people with diabetes, but the medication schedule must be adjusted first &mdash;
  especially insulin and sulphonylureas. Speak to your physician a couple of weeks before, not on the day.
</p>

<h3>Pregnancy</h3>
<p>
  Sugar and blood pressure control before conception matters more than at any other time, and several common tablets
  must be changed before pregnancy. This is planned jointly with the <a href="/department/anc.php">antenatal care
  team</a>. Gestational diabetes also means a substantially raised lifetime risk of type 2 diabetes, so an annual
  screening test after delivery is not optional.
</p>

<h3>Before surgery</h3>
<p>
  Tell the surgical and anaesthesia teams about every medicine you take. Metformin, SGLT2 inhibitors and insulin all
  need specific handling around the fasting period &mdash; something our
  <a href="/department/surgery.php">surgical team</a> reviews at the pre-operative visit.
</p>


  <table class="post__table">
    <thead>
      <tr><th>Measurement</th><th>Usual target</th><th>How often</th></tr>
    </thead>
    <tbody>
      <tr><td>HbA1c</td><td>Below 7% for most adults</td><td>Every 3 months until stable, then 6-monthly</td></tr>
      <tr><td>Fasting sugar</td><td>80&ndash;130 mg/dL</td><td>As advised, plus home monitoring</td></tr>
      <tr><td>Post-meal sugar</td><td>Below 180 mg/dL at 2 hours</td><td>As advised</td></tr>
      <tr><td>Blood pressure</td><td>Below 130/80 mmHg</td><td>Every visit, plus home readings</td></tr>
      <tr><td>LDL cholesterol</td><td>Below 100 mg/dL, lower if heart disease</td><td>Annually</td></tr>

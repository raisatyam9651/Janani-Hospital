<h2>What has not changed</h2>

<p>
  Egg quality still falls with age, and no laboratory technique reverses that. Success still depends on an accurate
  diagnosis first: thyroid disease, PCOS, endometriosis, tubal blockage, fibroids and male-factor problems each have
  their own treatment, and several of them are better addressed before IVF than during it. Many couples treated at our
  <a href="/department/infertility.php">infertility clinic</a> conceive with ovulation induction, corrective
  <a href="/department/laparoscopy.php">laparoscopic surgery</a> or IUI, without ever needing IVF.
</p>

<p>
  Weight, smoking, alcohol, sleep and diabetes control genuinely affect outcomes for both partners, and they are the
  parts of the process you control. Three months of preparation before a cycle is not wasted time.
</p>


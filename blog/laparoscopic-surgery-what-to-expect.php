<p class="post__lede">
  Keyhole surgery replaced a 15 cm incision with three or four cuts under a centimetre each. The operation inside the
  abdomen is the same one &mdash; the gallbladder, appendix or fibroid still has to come out &mdash; but almost
  everything about the recovery is different. Here is the whole journey, from the consultation to the day you go back
  to work.
</p>

<h2>What laparoscopic surgery actually is</h2>

<p>
  The abdomen is gently inflated with carbon dioxide to create working space. A camera the width of a pen goes in
  through one small cut near the navel and projects a magnified image onto a screen; fine instruments work through two
  or three other cuts. The surgeon operates while watching the monitor, at a level of magnification that is better,
  not worse, than the naked eye through an open incision.
</p>

<p>
  At Janani Hospital, the <a href="/department/laparoscopy.php">laparoscopy department</a> uses this approach for
  gallbladder removal, appendicectomy, hernia repair, ovarian cysts, ectopic pregnancy, hysterectomy, fibroid surgery,
  diagnostic laparoscopy for infertility, and selected colorectal, urological and bariatric procedures.
</p>

<h2>Before surgery</h2>

<h3>The consultation</h3>
<p>
  Expect an examination, imaging (usually ultrasound or CT), and a frank discussion of whether surgery is the right
  answer at all. Ask what happens if you wait, what the alternatives are, and what the plan is if the operation cannot
  be completed laparoscopically. Conversion to an open incision is uncommon but it is a legitimate safety decision, not
  a complication &mdash; usually because of dense adhesions from previous surgery or unclear anatomy.
</p>

<h3>Pre-operative tests</h3>
<ul>
  <li>Blood count, blood group, sugar, kidney and liver function, and clotting studies.</li>
  <li>ECG and a chest X-ray, particularly over 40 or with any heart or lung condition.</li>
  <li>An anaesthesia review, where you should mention every regular medication, herbal preparation, allergy, previous anaesthetic reaction, loose teeth, and any history of snoring or sleep apnoea.</li>
</ul>

<h3>The week before</h3>
<ul>
  <li><strong>Blood thinners</strong> (aspirin, clopidogrel, warfarin) may need stopping several days in advance &mdash; only ever on your doctor&rsquo;s instruction, never on your own.</li>
  <li><strong>Diabetes medication</strong> including metformin and insulin will be adjusted for the fasting period.</li>
  <li><strong>Stop smoking</strong> &mdash; even two weeks makes a measurable difference to wound healing and chest complications.</li>
  <li>Arrange someone to bring you home and stay the first night.</li>
</ul>

<div class="post__callout">
  <h3><svg class="icon"><use href="#i-check-circle"></use></svg> Fasting instructions</h3>
  <p>
    Usually no solid food for six hours and no clear fluids for two hours before surgery. Fasting from the previous
    evening is no longer necessary in most cases and leaves you dehydrated. Follow the exact timing given by your
    anaesthetist, and tell the ward if you accidentally ate or drank &mdash; it is a safety issue, not a scolding.
  </p>
</div>

<h2>On the day</h2>

<ol>
  <li><strong>Admission and marking.</strong> Consent is confirmed, the site is marked, and jewellery, dentures and nail polish are removed.</li>
  <li><strong>Anaesthesia.</strong> Almost all laparoscopic surgery is under general anaesthetic. You will be asleep within about 30 seconds of the injection and will not be aware of anything until you wake in recovery.</li>
  <li><strong>The procedure.</strong> A gallbladder removal typically takes 45&ndash;90 minutes; a laparoscopic hysterectomy or complex hernia repair, longer. Add roughly an hour either side for anaesthesia and recovery.</li>
  <li><strong>Recovery room.</strong> One to two hours of monitoring before you return to the ward. Some throat discomfort from the breathing tube and some nausea are common and settle quickly.</li>
  <li><strong>Same evening.</strong> You will be encouraged to sip fluids and, in most cases, to sit up and walk a short distance. Early mobilisation is one of the main reasons keyhole recovery is fast &mdash; it reduces clots and chest infections.</li>
</ol>


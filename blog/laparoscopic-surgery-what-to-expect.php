<h3>Shoulder-tip pain is normal</h3>
<p>
  A surprising ache at the tip of the shoulder in the first day or two is caused by residual carbon dioxide irritating
  the diaphragm, which shares a nerve supply with the shoulder. It is not a heart or shoulder problem. Walking, warm
  compresses and simple painkillers clear it within 24&ndash;48 hours.
</p>

<h3>Wound care</h3>
<ul>
  <li>Keep the dressings clean and dry as advised; most modern dressings allow a short shower after 48 hours.</li>
  <li>Do not apply oil, turmeric paste or home remedies to the wounds.</li>
  <li>Most units use absorbable sutures, so there may be nothing to remove.</li>
  <li>Slight bruising and firmness under a wound is normal for a few weeks.</li>
</ul>

<h3>Eating and moving</h3>
<p>
  Start with light, home-cooked food and build up as appetite returns. After gallbladder removal, most people
  eventually eat normally, but very oily food in the first few weeks often causes loose stools &mdash; introduce fat
  gradually. Walk several short distances a day rather than one long one, and avoid straining or lifting anything
  heavier than about five kilograms until cleared.
</p>


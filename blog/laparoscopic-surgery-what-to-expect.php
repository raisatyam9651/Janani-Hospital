<h2>Why keyhole, when it is suitable</h2>

<ul>
  <li>Substantially less post-operative pain and lower painkiller requirement</li>
  <li>One to two days in hospital instead of five to seven</li>
  <li>Return to work in one to two weeks rather than four to six for most procedures</li>
  <li>Far lower rates of wound infection and incisional hernia</li>
  <li>Small scars, which matters more to patients than surgeons often assume</li>
</ul>

<p>
  It is not right for everyone. Extensive adhesions from previous open surgery, severe cardiac or respiratory disease
  that makes the inflated abdomen risky, uncontrolled bleeding disorders, or very advanced disease may all make an open
  operation the safer choice. That judgement is made case by case with you, before the day of surgery.
</p>


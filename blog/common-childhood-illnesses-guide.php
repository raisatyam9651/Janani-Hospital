  <h3><svg class="icon"><use href="#i-alert-triangle"></use></svg> Warning signs of dehydration</h3>
  <p>
    Sunken eyes, no tears, dry mouth, no urine for six to eight hours, unusual sleepiness, or skin that stays pinched
    when released. Blood in the stool, persistent green vomiting, or a swollen tender abdomen all need to be seen
    urgently.
  </p>
</div>

<h2>4. Ear pain</h2>

<p>
  Middle ear infection often follows a cold, and typically causes pain that is worse lying down. A baby who cannot say
  so may instead pull at the ear, cry during feeds, or sleep badly for no other apparent reason.
</p>

<p>
  Many mild cases settle with pain relief alone, which is why a doctor may examine the eardrum and advise waiting 48
  hours before starting an antibiotic. Discharge from the ear, swelling or tenderness of the bone behind the ear,
  fever with severe pain, or any hearing concern should be seen promptly. Never put oil or drops into an ear that is
  discharging without a doctor looking at it first.
</p>

<h2>5. Rashes</h2>

<p>
  Most childhood rashes are viral and settle on their own. The ones that matter are distinguishable by a few features:
</p>

<ul>
  <li><strong>Blanching rash</strong> (fades when pressed with a glass) with a well child &mdash; usually viral, watch and wait.</li>
  <li><strong>Non-blanching purple spots or bruise-like patches</strong> with fever &mdash; a medical emergency; come to the hospital immediately.</li>
  <li><strong>Itchy raised weals</strong> that come and go &mdash; usually urticaria; but with any swelling of the lips, tongue or face, or difficulty breathing, treat as an emergency.</li>
  <li><strong>Blisters in crops with fever</strong> &mdash; likely chickenpox; keep the child away from newborns, pregnant women and anyone immunosuppressed.</li>
  <li><strong>Rash with high fever for five days plus red eyes, cracked lips and swollen hands</strong> &mdash; needs same-day assessment.</li>
</ul>

<h2>Prevention beats treatment</h2>

<ul>
  <li><strong>Keep immunisations on schedule.</strong> Measles, rotavirus, pneumococcus, Hib and typhoid vaccines prevent the illnesses that most often lead to hospital admission in this age group. If doses have been missed, catch-up schedules exist &mdash; ask rather than assuming it is too late.</li>
  <li><strong>Handwashing with soap</strong> before meals and after the toilet, for the whole household.</li>
  <li><strong>Safe drinking water</strong> &mdash; boiled or filtered &mdash; particularly through the monsoon months.</li>
  <li><strong>Nutrition:</strong> iron- and protein-rich food, plus vitamin D. Anaemia is common and makes every infection worse.</li>
  <li><strong>Growth monitoring.</strong> A child whose weight has plateaued needs review even without any obvious illness.</li>
</ul>


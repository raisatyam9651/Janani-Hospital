<p class="post__lede">
  A healthy child under five will pick up six to eight infections a year. Most of them need patience, fluids and a
  thermometer &mdash; not antibiotics. The skill parents need is not diagnosing the illness, but recognising the small
  number of signs that mean a child should be seen today.
</p>

<p>
  This guide covers the five complaints we see most often in the outpatient department, what genuinely helps at home,
  and the red flags for each one. If your instinct says something is wrong even though the list below says otherwise,
  trust the instinct and bring the child in. Parents are usually right.
</p>

<h2>1. Fever</h2>

<p>
  Fever is a response, not a disease. A temperature of 38&deg;C (100.4&deg;F) or more measured properly means the
  immune system is working; how high it goes correlates poorly with how serious the cause is. A child with 39&deg;C who
  is drinking, playing between spikes and passing urine is usually far less worrying than a child with 38&deg;C who is
  limp and refusing all fluids.
</p>

<h3>At home</h3>
<ul>
  <li>Paracetamol 15 mg per kg of body weight, no more often than every six hours &mdash; dose by <strong>weight</strong>, not age, and write down the time of each dose.</li>
  <li>Offer fluids constantly in small amounts. Watch wet nappies or trips to the toilet as your hydration gauge.</li>
  <li>Light clothing and a normal room temperature. Do not sponge with cold water or use ice; it causes shivering, which raises the core temperature.</li>
  <li>No aspirin for children, and no antibiotic left over from a previous illness.</li>
</ul>

<div class="post__callout post__callout--warn">
  <h3><svg class="icon"><use href="#i-alert-triangle"></use></svg> Bring a feverish child in the same day if</h3>
  <ul>
    <li>The child is under three months old and has any fever at all</li>
    <li>Fever has lasted more than three days, or returns after settling for a day</li>
    <li>The child is unusually drowsy, floppy, difficult to wake or inconsolably irritable</li>
    <li>There is fast or laboured breathing, chest indrawing, or grunting</li>
    <li>There is a rash that does not fade when pressed with a clear glass</li>
    <li>There is a seizure, a stiff neck, or repeated vomiting with severe headache</li>
    <li>No urine for eight hours, no tears when crying, or a sunken soft spot in a baby</li>
  </ul>
</div>

<h2>2. Cough and cold</h2>

<p>
  Almost all are viral. A cold typically peaks around day three and improves by day seven to ten, though a dry cough
  can linger two to three weeks afterwards &mdash; that tail is normal and is not a reason for a second antibiotic
  course.
</p>

<h3>At home</h3>
<ul>
  <li>Saline nose drops before feeds and sleep, especially in infants who cannot blow their nose.</li>
  <li>Warm fluids, and honey for children over one year (never under one, because of infant botulism risk).</li>
  <li>Steam inhalation only under close supervision &mdash; scald burns from a tipped vessel are a real and frequent injury.</li>
  <li>Avoid over-the-counter cough and cold syrups in young children; they are not effective and can be harmful.</li>
</ul>

<p>
  Wheeze that recurs with every cold, cough that is worse at night or after running, or a family history of asthma
  deserves an assessment at the <a href="/department/pediatrics.php">pediatrics department</a> rather than repeated
  cycles of syrup.
</p>

<h2>3. Diarrhoea and vomiting</h2>

<p>
  In loose motions, the danger is almost never the infection &mdash; it is dehydration. The single most important
  treatment is oral rehydration solution (ORS), given in small, frequent sips rather than large drinks that trigger
  more vomiting.
</p>

<h3>At home</h3>
<ul>
  <li>ORS after every loose stool: roughly 50&ndash;100 ml for a child under two, 100&ndash;200 ml for an older child.</li>
  <li>Give it a teaspoon at a time every one to two minutes if the child is vomiting. Small volumes stay down.</li>
  <li><strong>Continue feeding.</strong> Keep breastfeeding, and continue normal food &mdash; curd rice, khichdi, banana, plain rice. Starving a child prolongs diarrhoea.</li>
  <li>Zinc supplements for 14 days shorten the episode and reduce recurrence; ask your pediatrician for the dose.</li>
  <li>Avoid soft drinks and packaged juices &mdash; the sugar load pulls more water into the gut.</li>
  <li>Do not give anti-motility medicines to children.</li>
</ul>


<p class="post__lede">
  Nobody feels their blood pressure rising. Nobody notices the first protein leaking into their urine, or the cervical
  cells that are changing but not yet cancerous. That is precisely the point of a preventive checkup: it looks for the
  problems that do not announce themselves until they are expensive to fix.
</p>

<p>
  Almost every serious condition we treat has a long silent phase &mdash; often five to fifteen years &mdash; in which
  it is detectable and treatable. Diabetes, hypertension, kidney disease, thyroid disorders, anaemia, fatty liver,
  cervical and breast cancer all sit in that category. A checkup is simply a scheduled look into that window.
</p>

<h2>What a good checkup actually includes</h2>

<p>
  A useful package is not the one with the longest list of tests. It is the one matched to your age, sex, family
  history and habits. Broadly:
</p>

<h3>Everyone, annually</h3>
<ul>
  <li>Height, weight, BMI, waist circumference and blood pressure</li>
  <li>Complete blood count &mdash; anaemia is very common and very correctable</li>
  <li>Fasting blood sugar and HbA1c</li>
  <li>Lipid profile</li>
  <li>Kidney function (creatinine, urea) and urine routine</li>
  <li>Liver function tests</li>
  <li>Thyroid profile (TSH)</li>
  <li>A consultation to interpret all of it &mdash; this is the part that turns numbers into decisions</li>
</ul>

<h3>Added by age and sex</h3>
<ul>
  <li><strong>Women 21+:</strong> Pap smear three-yearly, or HPV testing five-yearly from 30. See our guide to <a href="/blog/womens-health-essential-checkups.php">essential checkups for women at every age</a>.</li>
  <li><strong>Women 40+:</strong> mammogram every one to two years; clinical breast examination annually.</li>
  <li><strong>Women at menopause:</strong> bone density (DEXA) and vitamin D.</li>
  <li><strong>Men 50+:</strong> prostate assessment, discussed with a <a href="/department/urology.php">urologist</a>.</li>
  <li><strong>Everyone 45+:</strong> ECG, and colorectal cancer screening as advised.</li>
  <li><strong>Smokers, or anyone with a strong family history:</strong> earlier and more frequent cardiac and cancer screening.</li>
</ul>

<div class="post__callout">
  <h3><svg class="icon"><use href="#i-check-circle"></use></svg> How to prepare for your checkup</h3>
  <ul>
    <li>Fast for 10&ndash;12 hours for sugar and lipid tests &mdash; water is allowed and encouraged.</li>
    <li>Take your regular morning medicines with a sip of water unless told otherwise; do not skip blood pressure tablets.</li>
    <li>Book a morning slot. Fasting samples are collected between 8 AM and 10 AM.</li>
    <li>Bring previous reports, however old. Trends are far more informative than a single reading.</li>
    <li>Bring a written list of every medicine and supplement you take.</li>
    <li>Women: avoid sample collection during menstruation for urine tests and Pap smear.</li>
    <li>Write down your questions beforehand. Consultations are short, and people forget the thing they came to ask.</li>
  </ul>
</div>

<h2>Reading your report without panicking</h2>

<p>
  A slightly out-of-range value is usually not an emergency. Reference ranges are set so that a proportion of perfectly
  healthy people fall outside them, and laboratory ranges differ between labs. What matters is the size of the
  abnormality, whether it is moving in a direction over time, and whether it fits with anything else in the report.
</p>

<p>
  Three practical rules:
</p>

<ol>
  <li><strong>Never start or stop a medicine based on a report alone.</strong> A raised sugar reading may be a lab error, a recent illness, or a genuine new diagnosis &mdash; the response is different for each.</li>
  <li><strong>Do not search individual values online before your consultation.</strong> Isolated numbers without context reliably produce the wrong answer and a bad night&rsquo;s sleep.</li>
  <li><strong>Keep every report in one folder</strong> (or photograph them into one phone album). The second checkup is worth much more than the first, because it shows direction.</li>
</ol>

<h2>The economics, plainly</h2>

<p>
  An annual preventive package costs a fraction of a single day in intensive care. Treating early hypertension costs a
  few hundred rupees a month; treating the stroke it causes costs a family its savings and often its earning member.
  Detecting cervical pre-cancer means an outpatient procedure; detecting cervical cancer means surgery, radiotherapy
  and chemotherapy.
</p>

<p>
  The same logic applies to time. A checkup is one morning a year. The conditions it catches take years off working
  life when they are found late.
</p>

<div class="post__callout post__callout--warn">
  <h3><svg class="icon"><use href="#i-alert-triangle"></use></svg> Do not wait for your annual checkup if you have</h3>
  <ul>
    <li>Unexplained weight loss, or persistent loss of appetite</li>
    <li>Chest discomfort or breathlessness on exertion</li>
    <li>A lump anywhere, or a mole that has changed</li>
    <li>Blood in urine, stool, sputum, or bleeding between periods</li>
    <li>A cough lasting more than three weeks</li>
    <li>Persistent fever, night sweats, or unusual fatigue</li>
    <li>A wound that is not healing, particularly if you are diabetic</li>
  </ul>
</div>

<h2>Who benefits most</h2>

<ul>
  <li><strong>Anyone over 30</strong> &mdash; metabolic disease appears roughly a decade earlier in South Asians than in Western screening guidelines assume.</li>
  <li><strong>Anyone with a family history</strong> of diabetes, heart disease, hypertension, thyroid disease or cancer.</li>
  <li><strong>Desk workers</strong> &mdash; sedentary work is an independent risk factor, regardless of body weight.</li>
  <li><strong>Women after a pregnancy complicated by gestational diabetes or high blood pressure</strong>, who carry a substantially raised lifetime risk and are very often lost to follow-up.</li>
  <li><strong>Anyone who smokes or drinks regularly</strong>, or has done in the past.</li>
</ul>

